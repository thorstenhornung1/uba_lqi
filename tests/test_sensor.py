    registry = er.async_get(hass)
    for unique_id in ("1117_component_1", "1117_component_5", "1117_component_9"):
        assert registry.async_get_entity_id("sensor", DOMAIN, unique_id), unique_id
    # Fehlende Komponente ist unavailable, existiert aber.
    assert _state(hass, "1117_component_5").state == "unavailable"


