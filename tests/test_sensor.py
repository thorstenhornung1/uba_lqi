async def test_entities_from_stored_metadata(
    hass: HomeAssistant, fake_api, config_entry, frozen_now
) -> None:
    """Entitäten entstehen aus den Metadaten, nicht aus der ersten Antwort."""
    # Erste Antwort enthält nur PM10 — NO2/PM2,5 fehlen gerade.
    fake_api.air["1117"] = air("1117", [component(1, 20.0, 1)])
