async def _setup(hass, config_entry):
    assert await hass.config_entries.async_setup(config_entry.entry_id)
    await hass.async_block_till_done()


def _state(hass, unique_id):
    entity_id = er.async_get(hass).async_get_entity_id("sensor", DOMAIN, unique_id)
    assert entity_id, f"entity {unique_id} not registered"
    return hass.states.get(entity_id)


async def test_station_and_combined_lqi(
    hass: HomeAssistant, fake_api, config_entry, frozen_now
) -> None:
    """Der Ozon-Fall: Bonn „gut", Köln wegen O3 „mäßig" — kombiniert „mäßig"."""
    await _setup(hass, config_entry)

    bonn = _state(hass, "1117_lqi")
    assert bonn.state == "good"
    assert bonn.attributes["worst_component"] == "pm10"
    assert bonn.attributes["all_components_reported"] is True

    koeln = _state(hass, "1114_lqi")
    assert koeln.state == "moderate"
    assert koeln.attributes["worst_component"] == "o3"

    combined = _state(hass, "test_entry_combined_lqi")
    assert combined.state == "moderate"
    assert combined.attributes["worst_component"] == "o3"
    assert combined.attributes["worst_component_station"] == "Köln-Rodenkirchen"
    # Je Komponente gewinnt die nächstgelegene Station: PM10 kommt aus Bonn.
    assert combined.attributes["components"]["pm10"]["station"] == "Bonn-Auerberg"
    assert combined.attributes["components"]["o3"]["station"] == "Köln-Rodenkirchen"


