async def test_station_meta_parsing(hass, aioclient_mock, frozen_now) -> None:
    """Stationsliste im positionsbasierten v4-Format."""
    aioclient_mock.get(
        META_URL,
        json={
            "stations": {
                "1117": [
                    "1117",
                    "DENW062",
                    "Bonn-Auerberg",
                    "Bonn",
                    "",
                    "1986-12-01",
                    None,
                    "7.0826",
                    "50.7536",
                    "10",
                    "2",
                    "1",
                    "NW",
                    "Nordrhein-Westfalen",
                    "vorstädtisches Gebiet",
                    "vorstädtisch",
                    "Hintergrund",
                    "An der Josefshöhe",
                    "",
                    "53117",
                ]
            },
            "components": {},
        },
    )
    client = UbaLqiApiClient(async_get_clientsession(hass))
    stations = await client.async_get_stations()
    station = stations["1117"]
    assert station.code == "DENW062"
    assert station.name == "Bonn-Auerberg"
    assert station.latitude == 50.7536
    assert station.longitude == 7.0826
    assert station.setting == "vorstädtisches Gebiet"
    assert station.station_type == "Hintergrund"


